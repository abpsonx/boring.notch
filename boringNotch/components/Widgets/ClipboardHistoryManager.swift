//
//  ClipboardHistoryManager.swift
//  boringNotch
//
//  Keeps a short in-memory history of copied text/images/files and new screenshots.
//  Nothing is written to disk except temporary image copies in the caches folder,
//  and items marked as concealed/transient (e.g. passwords from password managers) are skipped.
//

import AppKit
import Combine
import Defaults
import Foundation
import UniformTypeIdentifiers

struct ClipboardItem: Identifiable, Equatable {
    enum Kind: Equatable {
        case text(String)
        case image(URL)       // temporary PNG copy in the caches folder
        case file(URL)
        case screenshot(URL)  // file inside the watched screenshot folder
    }

    let id = UUID()
    let kind: Kind
    let date: Date
    let sourceApp: String?
    var thumbnail: NSImage?

    var isImage: Bool {
        switch kind {
        case .image, .screenshot: return true
        case .file(let url): return UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) ?? false
        case .text: return false
        }
    }

    /// Kind only (never the content) for diagnostics.
    var logKind: String {
        switch kind {
        case .text: return "text"
        case .image: return "image"
        case .file: return "file"
        case .screenshot: return "screenshot"
        }
    }

    var fileURL: URL? {
        switch kind {
        case .image(let url), .file(let url), .screenshot(let url): return url
        case .text: return nil
        }
    }

    var title: String {
        switch kind {
        case .text(let text):
            return text.trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ")
        case .image: return "Image"
        case .file(let url): return url.lastPathComponent
        case .screenshot(let url): return url.deletingPathExtension().lastPathComponent
        }
    }

    static func == (lhs: ClipboardItem, rhs: ClipboardItem) -> Bool {
        lhs.id == rhs.id && lhs.kind == rhs.kind
    }
}

@MainActor
final class ClipboardHistoryManager: ObservableObject {
    static let shared = ClipboardHistoryManager()

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var screenshotFolder: URL?
    @Published var lastCopiedID: UUID?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var pollTimer: Timer?
    private var cancellables = Set<AnyCancellable>()

    private var folderSource: DispatchSourceFileSystemObject?
    private var folderAccessStarted = false
    private var knownScreenshotPaths = Set<String>()
    private var rescanTask: Task<Void, Never>?

    private let imageCacheDirectory: URL = {
        let url = temporaryDirectory.appendingPathComponent("ClipboardHistory", isDirectory: true)
        try? FileManager.default.removeItem(at: url)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }()

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        Defaults.publisher(.clipboardHistoryEnabled)
            .sink { [weak self] change in
                Task { @MainActor in
                    guard let self else { return }
                    change.newValue ? self.startPolling() : self.stopPolling()
                }
            }
            .store(in: &cancellables)

        Publishers.Merge(
            Defaults.publisher(.watchScreenshots, options: []).map { _ in () },
            Defaults.publisher(.screenshotFolderBookmark, options: []).map { _ in () }
        )
            .sink { [weak self] _ in
                Task { @MainActor in self?.restartScreenshotWatcher() }
            }
            .store(in: &cancellables)
        restartScreenshotWatcher()

        Defaults.publisher(.clipboardHistoryLimit, options: [])
            .sink { [weak self] _ in
                Task { @MainActor in self?.trim() }
            }
            .store(in: &cancellables)
    }

    // MARK: - Pasteboard polling

    private func startPolling() {
        guard pollTimer == nil else { return }
        NSLog("Clipboard history: watching the clipboard")
        lastChangeCount = pasteboard.changeCount
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.checkPasteboard() }
        }
    }

    private func stopPolling() {
        pollTimer?.invalidate()
        pollTimer = nil
        items.removeAll { if case .screenshot = $0.kind { return false } else { return true } }
    }

    private func checkPasteboard() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let url = urls.first
        {
            insert(ClipboardItem(kind: .file(url), date: Date(), sourceApp: source, thumbnail: thumbnail(forFile: url)))
            return
        }

        if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
           let image = NSImage(pasteboard: pasteboard),
           let url = saveImage(image)
        {
            insert(ClipboardItem(kind: .image(url), date: Date(), sourceApp: source, thumbnail: image.thumbnail(maxSize: 160)))
            return
        }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            insert(ClipboardItem(kind: .text(text), date: Date(), sourceApp: source))
        }
    }

    private func insert(_ item: ClipboardItem) {
        NSLog("Clipboard history: captured \(item.logKind)")
        // Move duplicates to the top instead of storing them twice.
        if let index = items.firstIndex(where: { $0.kind == item.kind }) {
            var existing = items.remove(at: index)
            existing.thumbnail = existing.thumbnail ?? item.thumbnail
            items.insert(existing, at: 0)
            return
        }
        items.insert(item, at: 0)
        trim()
    }

    private func trim() {
        let limit = max(5, Defaults[.clipboardHistoryLimit])
        while items.count > limit {
            let removed = items.removeLast()
            if case .image(let url) = removed.kind {
                try? FileManager.default.removeItem(at: url)
            }
        }
    }

    // MARK: - Actions

    /// Puts the item back on the clipboard so it can be pasted with ⌘V.
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image(let url), .screenshot(let url):
            let wrote = withFolderAccess(url) { url -> Bool in
                guard let image = NSImage(contentsOf: url) else { return false }
                return pasteboard.writeObjects([image])
            }
            if !wrote { pasteboard.writeObjects([url as NSURL]) }
        case .file(let url):
            pasteboard.writeObjects([url as NSURL])
        }
        // Don't record our own write as a new entry.
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            let moved = items.remove(at: index)
            items.insert(moved, at: 0)
        }
        lastCopiedID = item.id
        Task { @MainActor in
            try? await Task.sleep(for: .seconds(1.5))
            if self.lastCopiedID == item.id { self.lastCopiedID = nil }
        }
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        if case .image(let url) = item.kind {
            try? FileManager.default.removeItem(at: url)
        }
    }

    func clear() {
        for item in items {
            if case .image(let url) = item.kind { try? FileManager.default.removeItem(at: url) }
        }
        items.removeAll()
    }

    func reveal(_ item: ClipboardItem) {
        guard let url = item.fileURL else { return }
        NSWorkspace.shared.activateFileViewerSelecting([url])
    }

    func itemProvider(for item: ClipboardItem) -> NSItemProvider {
        switch item.kind {
        case .text(let text):
            return NSItemProvider(object: text as NSString)
        case .image(let url), .file(let url), .screenshot(let url):
            return NSItemProvider(contentsOf: url) ?? NSItemProvider(object: url as NSURL)
        }
    }

    // MARK: - Screenshot folder

    /// Asks the user for the screenshot folder (needed because the app is sandboxed).
    func chooseScreenshotFolder() {
        let panel = NSOpenPanel()
        panel.canChooseDirectories = true
        panel.canChooseFiles = false
        panel.allowsMultipleSelection = false
        panel.prompt = "Watch Folder"
        panel.message = "Choose the folder where macOS saves your screenshots (usually Desktop)"
        panel.directoryURL = Self.defaultScreenshotFolder
        NSApp.activate(ignoringOtherApps: true)
        guard panel.runModal() == .OK, let url = panel.url else { return }
        do {
            let bookmark = try url.bookmarkData(options: .withSecurityScope, includingResourceValuesForKeys: nil, relativeTo: nil)
            Defaults[.screenshotFolderBookmark] = bookmark
        } catch {
            NSLog("Failed to save screenshot folder bookmark: \(error)")
        }
    }

    func forgetScreenshotFolder() {
        Defaults[.screenshotFolderBookmark] = nil
    }

    private static var defaultScreenshotFolder: URL {
        // In the sandbox, FileManager returns the container's Desktop, so build the real path.
        if let pw = getpwuid(getuid()), let home = pw.pointee.pw_dir {
            return URL(fileURLWithPath: String(cString: home)).appendingPathComponent("Desktop", isDirectory: true)
        }
        return URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent("Desktop", isDirectory: true)
    }

    private func restartScreenshotWatcher() {
        folderSource?.cancel()
        folderSource = nil
        rescanTask?.cancel()
        if let folder = screenshotFolder, folderAccessStarted {
            folder.stopAccessingSecurityScopedResource()
            folderAccessStarted = false
        }
        screenshotFolder = nil
        knownScreenshotPaths.removeAll()
        items.removeAll { if case .screenshot = $0.kind { return true } else { return false } }

        guard Defaults[.watchScreenshots], let bookmark = Defaults[.screenshotFolderBookmark] else { return }

        var isStale = false
        guard let folder = try? URL(resolvingBookmarkData: bookmark, options: .withSecurityScope, relativeTo: nil, bookmarkDataIsStale: &isStale) else {
            Defaults[.screenshotFolderBookmark] = nil
            return
        }
        if isStale, let fresh = try? folder.bookmarkData(options: .withSecurityScope, includingResourceValuesForKeys: nil, relativeTo: nil) {
            Defaults[.screenshotFolderBookmark] = fresh
            return // publisher fires again with the fresh bookmark
        }

        folderAccessStarted = folder.startAccessingSecurityScopedResource()
        screenshotFolder = folder

        // Show the most recent existing screenshots right away.
        let existing = scanScreenshots(in: folder)
        knownScreenshotPaths = Set(existing.map(\.path))
        for url in existing.prefix(5).reversed() {
            insertScreenshot(url)
        }

        let fd = open(folder.path, O_EVTONLY)
        guard fd >= 0 else { return }
        let source = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: .write, queue: .main)
        source.setEventHandler { [weak self] in
            Task { @MainActor in self?.scheduleRescan() }
        }
        source.setCancelHandler { close(fd) }
        source.resume()
        folderSource = source
    }

    private func scheduleRescan() {
        rescanTask?.cancel()
        rescanTask = Task { @MainActor in
            // macOS writes the file a moment after the folder changes.
            try? await Task.sleep(for: .milliseconds(800))
            guard !Task.isCancelled, let folder = screenshotFolder else { return }
            let current = scanScreenshots(in: folder)
            for url in current.reversed() where !knownScreenshotPaths.contains(url.path) {
                knownScreenshotPaths.insert(url.path)
                insertScreenshot(url)
            }
        }
    }

    private func insertScreenshot(_ url: URL) {
        let item = ClipboardItem(kind: .screenshot(url), date: creationDate(of: url) ?? Date(), sourceApp: "Screenshot", thumbnail: thumbnail(forFile: url))
        insert(item)
    }

    /// Screenshot files in the folder, newest first.
    private func scanScreenshots(in folder: URL) -> [URL] {
        let keys: [URLResourceKey] = [.creationDateKey, .isRegularFileKey]
        guard let urls = try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: keys, options: [.skipsHiddenFiles]) else {
            return []
        }
        return urls
            .filter { ["png", "jpg", "jpeg", "heic", "tiff"].contains($0.pathExtension.lowercased()) && isScreenshot($0) }
            .sorted { (creationDate(of: $0) ?? .distantPast) > (creationDate(of: $1) ?? .distantPast) }
    }

    private func isScreenshot(_ url: URL) -> Bool {
        // macOS tags screenshots with this extended attribute.
        if getxattr(url.path, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) > 0 {
            return true
        }
        let name = url.lastPathComponent.lowercased()
        return ["screenshot", "screen shot", "cuplikan layar", "bildschirmfoto", "capture d"].contains { name.hasPrefix($0) }
    }

    private func creationDate(of url: URL) -> Date? {
        try? url.resourceValues(forKeys: [.creationDateKey]).creationDate
    }

    // MARK: - Helpers

    private func withFolderAccess<T>(_ url: URL, _ body: (URL) -> T) -> T {
        let started = url.startAccessingSecurityScopedResource()
        defer { if started { url.stopAccessingSecurityScopedResource() } }
        return body(url)
    }

    private func saveImage(_ image: NSImage) -> URL? {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:])
        else { return nil }
        // The caches folder can be emptied by macOS or cleaner apps at any time.
        try? FileManager.default.createDirectory(at: imageCacheDirectory, withIntermediateDirectories: true)
        let url = imageCacheDirectory.appendingPathComponent("\(UUID().uuidString).png")
        do {
            try png.write(to: url)
            return url
        } catch {
            NSLog("Clipboard history: couldn't save image: \(error.localizedDescription)")
            return nil
        }
    }

    private func thumbnail(forFile url: URL) -> NSImage? {
        withFolderAccess(url) { url in
            if UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true,
               let image = NSImage(contentsOf: url)
            {
                return image.thumbnail(maxSize: 160)
            }
            return NSWorkspace.shared.icon(forFile: url.path)
        }
    }
}

private extension NSImage {
    func thumbnail(maxSize: CGFloat) -> NSImage {
        let ratio = min(maxSize / max(size.width, 1), maxSize / max(size.height, 1), 1)
        let target = NSSize(width: size.width * ratio, height: size.height * ratio)
        let result = NSImage(size: target)
        result.lockFocus()
        draw(in: NSRect(origin: .zero, size: target), from: .zero, operation: .copy, fraction: 1)
        result.unlockFocus()
        return result
    }
}
